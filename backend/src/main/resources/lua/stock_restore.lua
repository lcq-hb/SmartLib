-- =============================================================================
-- SmartLib 库存额度回补脚本（Redis + Lua）
--
-- 什么时候用：借阅归还、或扣减失败后的补偿，需要把额度还回 Redis 的预扣池。
--
-- 为什么必须用 Lua（而不是直接 INCRBY）：
--   INCRBY 对**不存在的 key** 会先创建再自增。如果 key 恰好过期/未预热，
--   归还 1 册会把一个"未知库存"写成 1 —— 真实库存可能是 10。
--   之后所有借阅都会被判成"库存不足"，比不回补更糟。
--   所以必须先 EXISTS 判断，再决定是否 INCRBY，且这两步必须原子。
--
--   （这里存在的窗口是：借阅侧 warmUp 用 SET 写入不带 NX，
--    与回补之间仍有一个极小的覆盖窗口；因为数据库是唯一事实来源、
--    且 warmUp 读的就是数据库当前值，最坏结果只是额度短暂偏大，
--    不会造成超卖 —— 扣减仍以数据库条件更新兜底。）
--
-- KEYS[1] = 库存 key，形如 smartlib:stock:{bookId}
-- ARGV[1] = 回补数量
--
-- 返回值约定：
--   >= 0  回补成功，返回回补后的额度
--   -1    key 不存在，未做任何修改（交给下次借阅的 warmUp 从数据库预热）
-- =============================================================================

local key = KEYS[1]
local qty = tonumber(ARGV[1])

if not qty or qty <= 0 then
    return -1
end

if redis.call('EXISTS', key) == 1 then
    return redis.call('INCRBY', key, qty)
end

return -1
