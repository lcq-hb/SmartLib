def build_intent_prompt(intents: dict[str, dict[str, str]]) -> str:
    lines = [f"- {key}：{meta['label']}" for key, meta in intents.items()]
    return INTENT_PROMPT.format(intents="\n".join(lines))


def build_arg_prompt(
    question: str, tool: str, schema: dict[str, Any], slots: dict[str, Any]
) -> str:
    import json

    return ARG_EXTRACT_PROMPT.format(
        question=question,
        tool=tool,
        schema=json.dumps(schema, ensure_ascii=False),
        slots=json.dumps(slots, ensure_ascii=False),
    )


def build_rag_prompt(context: str) -> str:
    return RAG_SYSTEM_PROMPT.format(context=context)


def build_final_answer_prompt(question: str, observations: str) -> str:
    return FINAL_ANSWER_PROMPT.format(question=question, observations=observations)


